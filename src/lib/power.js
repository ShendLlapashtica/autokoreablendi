// "가솔린 2.5 터보 AWD", "530i M 스포츠", "디젤 2.2 4WD", "P400 AB". So power is
// read off the trim against the manufacturer's rated output for that engine in
// that model generation. Each figure below is the maker's own rating (metric PS,
// Korean-market spec), not an estimate from the listing.
//
// Rules over guesses: a car that matches no rule gets powerPs = null, never a
// nearby number. Where a facelift changed the output inside one generation the
// rule is year-gated, and the facelift year itself is left out when it could
// be either -- a blank is honest, a wrong figure on a car someone is about to
// import is not.

