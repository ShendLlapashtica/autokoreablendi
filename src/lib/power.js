// Engine power (PS) for an Encar listing.
//
// Encar does not publish power. Verified 2026-10-01 against every source it
// exposes for one car: the search row, /v1/readside/vehicle (spec block:
// displacement, fuel, gearbox, body class), and the official inspection record
// (/v1/readside/inspection: VIN, engine code "B46B20A") -- no PS, hp or kW in
// any of them.
//
