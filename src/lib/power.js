// Land Rover / Jaguar and Volvo name the engine by its rating outright:
// "P400" is 400 PS, "D300" is 300 PS. Volvo's codes are fixed outputs.
const VOLVO = { B4: 197, B5: 250, B6: 300, T4: 190, T5: 254, T6: 320, D4: 190, D5: 235 };
const CODE_RATED = new Set(['랜드로버', '재규어']);

const COMPILED = RULES.map(([mk, model, engine, ps, opt = {}]) => ({
  mk, model: r(model), engine: r(engine), ps,
  fuel: opt.fuel ? r(opt.fuel) : null, yFrom: opt.yFrom ?? null, yTo: opt.yTo ?? null,
}));

function carYear(car) {
  const y = parseInt(String(car.FormYear || car.Year || '').slice(0, 4), 10);
  return Number.isFinite(y) ? y : null;
}

function result(ps, basis) {
  return { powerPs: ps, powerKw: Math.round(ps * KW_PER_PS), powerSource: 'manufacturer-spec', powerBasis: basis };
}

/** The manufacturer-rated output for this Encar row, or null when unknown. */
export function powerFor(car) {
  if (!car) return null;
  const mk    = String(car.Manufacturer || '');
  const model = String(car.Model || '').trim();
  let trim    = `${car.Badge || ''} ${car.BadgeDetail || ''}`.replace(/\s+/g, ' ').trim();
  // Encar often puts the drivetrain in the MODEL instead of the trim
  // ("그랜저 하이브리드 (GN7)" / "캘리그래피"), so carry it across.
  if (/하이브리드/.test(model) && !/하이브리드|HEV/.test(trim)) trim += ' 하이브리드';
  const fuel  = String(car.FuelType || '');
  const year  = carYear(car);
  const basis = `${model} ${trim}`.trim();

  // Some sellers state it outright: "2.0 TD4 SE (150마력)". That pins the exact
  // variant, so it beats any rule below.
  const stated = trim.match(/(\d{2,4})\s*마력/);
  if (stated) return { ...result(Number(stated[1]), basis), powerSource: 'listing' };

  if (CODE_RATED.has(mk)) {
    const m = trim.match(/\b[PD](\d{3})\b/);
    if (m) return result(Number(m[1]), basis);
    if (/SDV6/.test(trim)) return result(306, basis);
    if (/SDV8/.test(trim)) return result(339, basis);
    if (/\bTD6\b/.test(trim)) return result(258, basis);
    if (/\bSD4\b/.test(trim)) return result(240, basis);
    if (/\bTD4\b/.test(trim)) return result(180, basis);
  }

  if (mk === '볼보') {
    const m = trim.match(/\b([BTD][4-6])\b/);
    // B5 is the one code sold as both a petrol (250) and a diesel (235).
    if (m && m[1] === 'B5' && /디젤/.test(fuel)) return result(235, basis);
    if (m && VOLVO[m[1]]) return result(VOLVO[m[1]], basis);
  }

  for (const rule of COMPILED) {
    if (rule.mk !== mk) continue;
    if (!rule.model.test(model)) continue;
    if (!rule.engine.test(trim)) continue;
    if (rule.fuel && !rule.fuel.test(fuel)) continue;
    if (rule.yFrom != null && (year == null || year < rule.yFrom)) continue;
    if (rule.yTo   != null && (year == null || year > rule.yTo))   continue;
    return rule.ps == null ? null : result(rule.ps, basis);
  }
  return null;
}

/** Adds powerPs / powerKw / powerSource to a row; untouched when unknown. */
export function withPower(car) {
  const p = powerFor(car);
  return p ? { ...car, ...p } : { ...car, powerPs: null, powerKw: null, powerSource: null };
}
